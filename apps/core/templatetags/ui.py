@register.simple_tag
def icon(name, size=18, cls=""):
    paths = ICONS.get(name, ICONS["box"])
    return format_html(
        '<svg class="icon {}" width="{}" height="{}" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
        'stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">{}</svg>',
        cls, size, size, mark_safe(paths),
    )


def _dec(value):
    try:
        return Decimal(str(value))
    except (InvalidOperation, TypeError, ValueError):
        return None


@register.filter
def num(value, decimales=2):
    d = _dec(value)
    if d is None:
        return value
    return f"{d:,.{int(decimales)}f}"


@register.filter
def money(value, decimales=2):
    d = _dec(value)
    if d is None:
        return value
    signo = "-" if d < 0 else ""
    return f"{signo}${abs(d):,.{int(decimales)}f}"


@register.filter
def pct(value, decimales=2):
    d = _dec(value)
    if d is None:
        return value
    return f"{d:.{int(decimales)}f}%"


@register.filter
def iniciales(nombre):
    partes = [p for p in str(nombre).split() if p]
    return "".join(p[0] for p in partes[:2]).upper() or "?"
